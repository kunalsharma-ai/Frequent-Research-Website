function phoneError(t, e, a = "") {
  const n = PHONE_COUNTRIES.find((i) => i.iso === t) || PHONE_COUNTRIES[0],
    s = e.replace(/\D/g, "");
  return s
    ? n.other && !/^\+\d{1,4}$/.test(a)
      ? "Enter your country code, like +880."
      : s.length < n.min || s.length > n.max
        ? n.min === n.max
          ? `${n.name} numbers have ${n.min} digits after ${n.code || "the country code"}.`
          : `Enter ${n.min} to ${n.max} digits after ${n.code || "the country code"}.`
        : n.start && !n.start.test(s)
          ? `This doesn't look like a valid ${n.name} mobile number.`
          : ""
    : "Enter your phone or WhatsApp number.";
}

