/* Build 79: land points for the 3D globe of the new design (src/design79/globeLand.js).
   Rasterises the site's own world map (RG_MAP in src/app/data/mapRegions.jsx, Natural Earth 110m, equirectangular
   1000x500) in Chromium, then keeps the points of an even (Fibonacci) sphere that fall on land.
   Usage: node tools/design79/make-globe-land.cjs [points=16000] */
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const src = fs.readFileSync(path.join(__dirname, '../../src/app/data/mapRegions.jsx'), 'utf8');
const s0 = src.slice(0, src.lastIndexOf('export')), body = s0.slice(s0.indexOf('{', s0.indexOf('RG_MAP')), s0.lastIndexOf('}') + 1);
const MAP = Function('return ' + body)();
const N = +(process.argv[2] || 16000);
(async () => {
  const b = await chromium.launch(fs.existsSync('/opt/pw-browsers/chromium') ? { executablePath: '/opt/pw-browsers/chromium' } : {});
  const p = await b.newPage();
  const pts = await p.evaluate(({ MAP, N }) => {
    const W = 2000, H = 1000, c = document.createElement('canvas');
    c.width = W; c.height = H;
    const g = c.getContext('2d');
    g.scale(W / MAP.w, H / MAP.h); g.fillStyle = '#000';
    for (const x of MAP.base) g.fill(new Path2D(x.d));
    const img = g.getImageData(0, 0, W, H).data, out = [];
    const ga = Math.PI * (3 - Math.sqrt(5));
    for (let i = 0; i < N; i++) {
      const y = 1 - (i / (N - 1)) * 2, lat = Math.asin(y) * 180 / Math.PI;
      let lon = ((i * ga) * 180 / Math.PI) % 360; if (lon > 180) lon -= 360;
      const px = Math.floor((lon + 180) / 360 * W), py = Math.floor((90 - lat) / 180 * H);
      if (img[(py * W + px) * 4 + 3] > 100 && lat > -60) out.push(Math.round(lat * 10), Math.round(lon * 10));
    }
    return out;
  }, { MAP, N });
  await b.close();
  const file = path.join(__dirname, '../../src/design79/globeLand.js');
  fs.writeFileSync(file, `/* generated by tools/design79/make-globe-land.cjs: [lat*10, lon*10, …] of ${pts.length / 2} land points */\nexport const GLOBE_LAND = ${JSON.stringify(pts)};\n`);
  console.log(pts.length / 2, 'points ->', file);
})();
