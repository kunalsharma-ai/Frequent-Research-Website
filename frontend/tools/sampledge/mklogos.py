import re, json, sys
src=__import__('sys').argv[1] if len(__import__('sys').argv)>1 else 'brand/products/'  # folder with the Sampledge product logo files
out=__import__('os').path.join(__import__('os').path.dirname(__file__),'..','..','src/data/SampledgeLogos65.jsx')
ps="zapx bidzo projexa sampleon dealflow talk2tax crew".split()
variants={'logo':'-logo.svg','dark':'-logo-dark-clear.svg','mark':'-mark.svg'}
def scope(svg, pre):
    svg=re.sub(r'<\?xml[^>]*>\s*','',svg)
    svg=re.sub(r'<title[^>]*>.*?</title>','',svg,flags=re.S)
    ids=re.findall(r'\bid="([^"]+)"',svg)
    for i in sorted(set(ids),key=len,reverse=True):
        svg=re.sub(r'\bid="%s"'%re.escape(i),'id="%s-%s"'%(pre,i),svg)
        svg=re.sub(r'url\(#%s\)'%re.escape(i),'url(#%s-%s)'%(pre,i),svg)
        svg=re.sub(r'href="#%s"'%re.escape(i),'href="#%s-%s"'%(pre,i),svg)
        svg=re.sub(r'aria-labelledby="%s"'%re.escape(i),'',svg)
    # keyframes
    kfs=re.findall(r'@keyframes\s+([\w-]+)',svg)
    for k in sorted(set(kfs),key=len,reverse=True):
        svg=re.sub(r'(?<![\w-])%s(?![\w-])'%re.escape(k),'%s-%s'%(pre,k),svg)
    # prefix selectors inside <style>
    def fixstyle(m):
        css=m.group(1)
        res=[];i=0
        def pref(sel):
            parts=[]
            for s in sel.split(','):
                s=s.strip()
                if not s: continue
                if s.startswith('@') or re.match(r'^(from|to|\d+%)',s): parts.append(s);continue
                parts.append('.%s %s'%(pre,s))
            return ','.join(parts)
        # tokenize top-level blocks
        out='';depth=0;buf=''
        j=0
        while j<len(css):
            c=css[j]
            if c=='{':
                head=buf.strip()
                if depth==0 and not head.startswith('@'): out+=pref(head)+'{'
                elif depth==1 and inmedia and not head.startswith('@'): out+=pref(head)+'{'
                else: out+=head+'{'
                if depth==0: inmedia=head.startswith('@media')
                depth+=1;buf=''
            elif c=='}':
                out+=buf+'}';buf='';depth-=1
            else: buf+=c
            j+=1
        return '<style>'+out+buf+'</style>'
    svg=re.sub(r'<style>(.*?)</style>',fixstyle,svg,flags=re.S)
    # "still" copy for small placements: the logo's own reduced-motion rules (plus the extras the -static files add),
    # applied under any .pr5-still ancestor
    def still(m):
        body=m.group(1)
        rules=re.findall(r'([^{}]+)\{([^{}]*)\}',body)
        extra=[('.%s .flash'%pre,'display:none'),('.%s .tg'%pre,'clip-path:none!important'),('.%s .uline'%pre,'stroke-dashoffset:0!important'),('.%s .lt'%pre,'opacity:1!important'),('.%s *'%pre,'animation:none!important')]
        css=''.join(','.join('.pr5-still '+x.strip() for x in sel.split(','))+'{'+dec+'}' for sel,dec in rules+extra)
        return m.group(0)+css
    svg=re.sub(r'@media \(prefers-reduced-motion:reduce\)\{((?:[^{}]*\{[^{}]*\})*)\}',still,svg)
    svg=re.sub(r'<svg\b','<svg class="%s"'%pre,svg,count=1)
    svg=re.sub(r'\s(width|height)="[^"]*"','',svg[:svg.index('>')+1],count=2)+svg[svg.index('>')+1:]
    svg=svg.replace('role="img"','aria-hidden="true" focusable="false"')
    svg=re.sub(r'\s*aria-labelledby="[^"]*"','',svg)
    return re.sub(r'>\s+<','><',svg.strip())
data={}
for p in ps:
    data[p]={}
    for v,suf in variants.items():
        s=open(src+p+suf,encoding='utf-8').read()
        data[p][v]=scope(s,'sxl-%s-%s'%(p,v))
js='''/*
 * Sampledge product logos (build 65 update 6). Prefix PR5_LOGO. Source: the Sampledge website build supplied by Kunal
 * (dist/brand/products/<id>-logo.svg, -logo-dark-clear.svg, -mark.svg; animated versions). Generated by
 * tools/sampledge/mklogos.py: ids, keyframes and style selectors are scoped per variant (sxl-<id>-<variant>) so several
 * logos can sit inline on one page without clashing. Inline (not <img>) so the logos use the page's Manrope/Inter fonts.
 */
const PR5_LOGOS = '''+json.dumps(data,ensure_ascii=False)+';\n'
open(out,'w',encoding='utf-8').write(js)
