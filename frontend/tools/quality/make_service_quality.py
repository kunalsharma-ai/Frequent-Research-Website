"""Build src/data/ServiceQuality65.jsx from the quality-process brief (markdown/plain text).
Usage: python3 tools/quality/make_service_quality.py <brief.md> src/data/ServiceQuality65.jsx
The brief holds three documents (Digital Marketing, IT & Development, Accounts & Finance) with the same shape:
title, subtitle, intro, then numbered sections; "Stage n:" and "A." sub-items; "* " bullets; "Quality control:" lines;
"Label: text" pairs; numbered "1. Label: text" steps; short headings above bullet groups."""
import json, re, sys

DOCS = [('digital-marketing', 'Digital Marketing Quality Process'), ('it-development', 'IT & Development Quality Process'), ('accounts-finance', 'Accounts & Finance Quality Process')]

def parse(lines):
    doc = {'title': lines[0], 'sub': lines[1], 'intro': [], 'secs': [], 'tag': ''}
    sec = None; item = None
    def tgt():
        return item if item is not None else (sec if sec is not None else None)
    def add(b):
        t = tgt()
        if t is None:
            doc['intro'].append(b['t']) if b['type'] == 'p' else None
            return
        bl = t['blocks']
        if b['type'] == 'li' and bl and bl[-1]['type'] == 'ul':
            bl[-1]['items'].append(b['t']); return
        if b['type'] == 'li':
            bl.append({'type': 'ul', 'items': [b['t']]}); return
        if b['type'] == 'step' and bl and bl[-1]['type'] == 'ol':
            bl[-1]['items'].append([b['k'], b['v']]); return
        if b['type'] == 'step':
            bl.append({'type': 'ol', 'items': [[b['k'], b['v']]]}); return
        if b['type'] == 'kv' and bl and bl[-1]['type'] == 'kv':
            bl[-1]['items'].append([b['k'], b['v']]); return
        if b['type'] == 'kv':
            bl.append({'type': 'kv', 'items': [[b['k'], b['v']]]}); return
        bl.append(b)
    raw = lines[2:]
    for i, ln in enumerate(raw):
        s = ln.strip()
        if not s:
            continue
        nxt = next((x.strip() for x in raw[i + 1:] if x.strip()), '')
        if s.startswith('Frequent Research –') or s.startswith('Frequent Research -'):
            doc['tag'] = s; continue
        m = re.match(r'^(\d+)\.\s+([^:]+)$', s)
        if m and not s.endswith('.'):
            sec = {'n': int(m.group(1)), 't': m.group(2).strip(), 'blocks': [], 'items': []}; doc['secs'].append(sec); item = None; continue
        m = re.match(r'^(Stage\s+\d+|[A-Z])[:.]\s+(.+)$', s)
        if m and sec is not None and len(s) < 90 and not s.endswith('.'):
            item = {'k': m.group(1).replace('Stage ', ''), 't': m.group(2).strip(), 'blocks': [], 'qc': ''}; sec['items'].append(item); continue
        if s.startswith('* '):
            add({'type': 'li', 't': s[2:].strip().rstrip('.') }); continue
        m = re.match(r'^Quality (?:control|gate|check):\s*(.+)$', s, re.I)
        if m and item is not None:
            item['qc'] = m.group(1).strip(); continue
        m = re.match(r'^\d+\.\s+([^:]{2,60}):\s+(.+)$', s)
        if m:
            add({'type': 'step', 'k': m.group(1).strip(), 'v': m.group(2).strip()}); continue
        m = re.match(r'^([A-Z][A-Za-z0-9 &/,\'()-]{2,60}):\s+(.+)$', s)
        if m:
            add({'type': 'kv', 'k': m.group(1).strip(), 'v': m.group(2).strip()}); continue
        if len(s) < 60 and not re.search(r'[.:;]$', s) and nxt.startswith('* '):
            add({'type': 'h', 't': s}); continue
        add({'type': 'p', 't': s})
    return doc

def main(src, dst):
    L = open(src, encoding='utf-8').read().split('\n')
    starts = []
    for k, title in DOCS:
        idx = next(i for i, x in enumerate(L) if x.strip() == title)
        starts.append((k, idx))
    out = {}
    for j, (k, a) in enumerate(starts):
        b = starts[j + 1][1] if j + 1 < len(starts) else next(i for i, x in enumerate(L) if i > a and x.strip().startswith('Frequent Research –')) + 1
        chunk = [x for x in L[a:b]]
        doc = parse([x.strip() for x in chunk if x.strip()][:2] + chunk[2:])
        out[k] = doc
    js = ('/*\n * Quality process content for Digital Marketing, IT & Development and Accounts & Finance (build 65, update 7).\n'
          ' * Generated by tools/quality/make_service_quality.py from the quality-process brief (Oct 2026). Prefix SQ7_.\n'
          ' * Used by src/pages/ServiceQuality65.jsx (web pages) and src/components/site/ServiceQualityPdf65.jsx (PDFs),\n'
          ' * so the page and the PDF always say the same thing. Re-run the script to update; do not edit by hand.\n */\n'
          'const SQ7_DOCS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
    open(dst, 'w', encoding='utf-8').write(js)
    for k, d in out.items():
        print(k, d['title'], '| secs', [(s['n'], s['t'][:28], len(s['items']), [b['type'] for b in s['blocks']]) for s in d['secs']], '| tag', d['tag'][:40])

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
