"""Build src/data/Reach18.jsx (update 18, About Us "Our reach") from the panel workbooks in public/data/panel-books:
regions + countries (55; healthcare 38 flagged), departments, and job-title families (B2B by audience + healthcare roles)."""
import json, glob, re, collections, os
R = os.path.join(os.path.dirname(__file__), '..', '..')
P = os.path.join(R, 'public/data/panel-books')
idx = json.load(open(os.path.join(P, 'index.json')))
hc = {c['slug'] for c in idx['hcp']}
regs = collections.OrderedDict()
order = ['Asia-Pacific', 'Europe', 'Middle East & Africa', 'North America', 'South America']
for r in order: regs[r] = []
for c in idx['b2c']:
    regs.setdefault(c['region'], []).append([c['name'], c['iso'], c['slug'], 1 if c['slug'] in hc else 0])
for r in regs: regs[r].sort(key=lambda x: x[0])
AUD = {'Agriculture industry audience': 'Agriculture', 'Service industry audience': 'Services', 'Manufacturing industry audience': 'Manufacturing', 'Government & defence audience': 'Government & defence'}
depts = collections.OrderedDict(); fam = collections.OrderedDict(); ind = collections.OrderedDict()
def clean(t):
    t = re.sub(r'\s*Profile$', '', t).replace('Rolesng Roles', 'Roles').replace(' Job Title', '')
    return t.strip()
for f in sorted(glob.glob(os.path.join(P, 'b2b/*.json'))):
    d = json.load(open(f))
    for g in d['groups']:
        a = AUD.get(g.get('title'))
        if not a: continue
        for t in g['tables']:
            tt = t['title']; rows = [r[0].strip() for r in t['rows']]
            if re.search(r'industry (distribution|profile)', tt, re.I):
                for x in rows: ind.setdefault(a, collections.OrderedDict())[x] = 1
            elif re.search(r'department', tt, re.I):
                for x in rows: depts[re.sub(r'Human Resource Department', 'Human Resources Department', re.sub(r'Mid Level', 'Mid-Level', x))] = 1
            else:
                fam.setdefault((a, clean(tt)), collections.OrderedDict()).update((x, 1) for x in rows)
for f in sorted(glob.glob(os.path.join(P, 'hc/hcp/*.json'))):
    d = json.load(open(f))
    for g in d['groups']:
        if not re.search(r'job title', g.get('title') or '', re.I) or re.search(r'AI', g.get('title') or ''): continue
        for t in g['tables']:
            m = re.match(r'(.+?)\s+—', t['title'])
            if not m: continue
            k = m.group(1).title().replace('&', '&').replace(' It', ' IT').replace('(Ancillary)', '(ancillary)')
            fam.setdefault(('Healthcare', k), collections.OrderedDict()).update((r[0].strip(), 1) for r in t['rows'])
fams = [[a, k, list(v)] for (a, k), v in fam.items()]
titles = len({x for f in fams for x in f[2]})
out = {
    'regions': [[r, v] for r, v in regs.items()],
    'departments': list(depts),
    'panelIndustries': [[a, list(v)] for a, v in ind.items()],
    'families': fams,
    'titles': titles,
}
src = '/* Build 65 update 18 — generated by tools/reach/make_reach.py from public/data/panel-books (do not edit by hand).\n   About Us "Our reach": regions + countries, departments, job-title families. */\nconst R18_DATA = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(R, 'src/data/Reach18.jsx'), 'w').write(src)
print('regions', [(r, len(v)) for r, v in regs.items()], 'depts', len(depts), 'families', len(fams), 'titles', titles, 'bytes', len(src))
print([ (a,k,len(v)) for a,k,v in fams if a=='Healthcare'])
